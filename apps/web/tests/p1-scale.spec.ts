import { expect, test } from '@playwright/test';
import { env } from 'node:process';

test('P1 real replay over 10000 completes, switches scope, resumes and cancels', async ({ page }) => {
  test.setTimeout(90000);
  await page.goto(env.D3_E2E_URL!);
  await page.getByLabel('角色令牌').fill(env.D3_E2E_TOKEN!);
  await page.getByRole('button', { name: '连接 / 刷新' }).click();
  await expect(page.getByRole('heading', { name: '已有事件回放' })).toBeVisible({ timeout: 3000 });
  await page.getByLabel('回放速率（EPS）').fill('1000');
  const created = page.waitForResponse(r => r.url().endsWith('/replays') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '创建回放', exact: true }).click();
  const replay = await (await created).json();
  await expect(page.getByTestId('active-session')).toContainText(replay.session_id);
  await page.getByRole('button', { name: '安全事件' }).click();
  const pending = page.waitForResponse(r => r.url().includes('/overview?'));
  await page.getByRole('button', { name: '刷新检测事件' }).click();
  expect((await (await pending).json()).input_mode).toBe('replay');
  await expect(page.getByText('检测覆盖不足，不能据此判断是否存在规则命中。')).toBeVisible();
  await page.getByRole('button', { name: '概览与导入' }).click();
  await expect(page.getByTestId('replay-status')).toContainText('completed', { timeout: 45000 });
  await expect(page.getByTestId('replay-status')).toContainText('10001 / 10001');
  await expect(page.getByTestId('replay-status')).toContainText('complete');
  await page.getByRole('button', { name: '刷新事件', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(20);
  await page.screenshot({ path: `${env.TRACE_E2E_ARTIFACTS}/replay-complete.png`, fullPage: true });
  await page.reload();
  await page.getByLabel('角色令牌').fill(env.D3_E2E_TOKEN!);
  await page.getByRole('button', { name: '连接 / 刷新' }).click();
  await page.getByLabel('回放作业 ID').fill(replay.job_id);
  await page.getByRole('button', { name: '打开回放' }).click();
  await expect(page.getByTestId('replay-status')).toContainText('10001 / 10001');
  await page.getByRole('button', { name: '返回导入会话' }).click();
  await expect(page.getByTestId('active-session')).toContainText(env.P1_SOURCE_SESSION!);
  await page.getByLabel('回放速率（EPS）').fill('1');
  await page.getByRole('button', { name: '创建回放', exact: true }).click();
  await expect(page.getByRole('button', { name: '取消回放', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '取消回放', exact: true }).click();
  await expect(page.getByTestId('replay-status')).toContainText('cancelled');
  await expect(page.getByTestId('replay-status')).toContainText('partial');
  await page.screenshot({ path: `${env.TRACE_E2E_ARTIFACTS}/replay-cancelled.png`, fullPage: true });
});

test('P1 uncertain POST retries one key; old event requests cannot cross sessions; viewer cannot create', async ({ page }) => {
  test.setTimeout(60000);
  await page.goto(env.D3_E2E_URL!);
  await page.getByLabel('角色令牌').fill(env.D3_E2E_TOKEN!);
  await page.getByRole('button', { name: '连接 / 刷新' }).click();
  await page.getByLabel('回放速率（EPS）').fill('1');
  const keys: string[] = [];
  const ids: string[] = [];
  await page.route('**/datasets/*/replays', async route => {
    keys.push(route.request().headers()['idempotency-key']);
    const response = await route.fetch();
    ids.push((await response.json()).job_id);
    if (keys.length === 1) await route.abort('failed');
    else await route.fulfill({ response });
  });
  await page.getByRole('button', { name: '创建回放', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试创建（同一请求）' })).toBeEnabled();
  await expect(page.getByLabel('回放速率（EPS）')).toBeDisabled();
  await page.getByRole('button', { name: '重试创建（同一请求）' }).click();
  await expect(page.getByTestId('replay-status')).toBeVisible();
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1]); expect(ids[0]).toBe(ids[1]);
  // Hold a real old-session response while the user returns to the import source.
  let release!: () => void;
  const hold = new Promise<void>(resolve => { release = resolve; });
  let arrived!: () => void;
  const waiting = new Promise<void>(resolve => { arrived = resolve; });
  await page.route('**/events?*', async route => {
    const response = await route.fetch(); arrived(); await hold;
    await route.fulfill({ response }).catch(() => {});
  });
  await page.getByRole('button', { name: '刷新事件', exact: true }).click();
  await waiting;
  await page.getByRole('button', { name: '返回导入会话' }).click();
  await expect(page.getByTestId('active-session')).toContainText(env.P1_SOURCE_SESSION!);
  release();
  await expect(page.getByText('尚未查询事件；请选择数据集后刷新。')).toBeVisible();
  await page.unroute('**/events?*');
  await page.getByRole('button', { name: '取消回放', exact: true }).click();
  await expect(page.getByTestId('replay-status')).toContainText('cancelled');
  await page.getByLabel('角色令牌').fill(env.D9_E2E_VIEWER!);
  await page.getByRole('button', { name: '连接 / 刷新' }).click();
  await page.unroute('**/datasets/*/replays');
  await page.getByRole('button', { name: '创建回放', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('403');
  await expect(page.getByTestId('replay-status')).toHaveCount(0);
  await page.screenshot({ path: `${env.TRACE_E2E_ARTIFACTS}/replay-forbidden.png`, fullPage: true });
});
